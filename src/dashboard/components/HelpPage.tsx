import { useEffect, useMemo, useRef, useState } from 'react';

interface Section {
  id: string;
  title: string;
  body: JSX.Element;
}

export function HelpPage() {
  const sections = useMemo<Section[]>(() => SECTIONS, []);
  const [activeId, setActiveId] = useState(sections[0]!.id);
  const scrollerRef = useRef<HTMLElement | null>(null);
  // Suppress scroll-spy briefly after a nav click — the programmatic smooth
  // scroll fires intersection events for every section it passes through,
  // which would yank the highlight to the wrong row before the target lands.
  const suppressUntilRef = useRef(0);

  useEffect(() => {
    const root = scrollerRef.current;
    if (!root) return;
    // Pick the section whose top sits in the upper third of the scroll area —
    // matches the user's reading position rather than whatever is geometrically
    // in the middle.
    const observer = new IntersectionObserver(
      (entries) => {
        if (Date.now() < suppressUntilRef.current) return;
        const visible = entries.filter((e) => e.isIntersecting);
        if (visible.length === 0) return;
        // Pick the topmost intersecting section — the one the user is reading.
        const top = visible.reduce((best, cur) =>
          cur.boundingClientRect.top < best.boundingClientRect.top ? cur : best,
        );
        const id = (top.target as HTMLElement).dataset.sectionId;
        if (id) setActiveId(id);
      },
      {
        root,
        // Top trigger line at 12% of the scroll area; bottom at 70% so short
        // sections still register as active when they sit in the middle.
        rootMargin: '-12% 0px -70% 0px',
        threshold: 0,
      },
    );
    const els = root.querySelectorAll<HTMLElement>('[data-section-id]');
    els.forEach((el) => observer.observe(el));
    return () => observer.disconnect();
  }, [sections]);

  function jumpTo(id: string) {
    setActiveId(id);
    // Smooth scroll typically completes in ~400–600ms; 800ms is a safe buffer.
    suppressUntilRef.current = Date.now() + 800;
    document
      .getElementById(`help-${id}`)
      ?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }

  return (
    <div className="col-span-2 grid h-full grid-cols-[240px_1fr] overflow-hidden bg-slate-50">
      <nav className="overflow-y-auto border-r border-slate-200 bg-white px-3 py-6">
        <h2 className="px-2 text-xs font-semibold uppercase tracking-wide text-slate-500">
          Разделы
        </h2>
        <ul className="mt-3 space-y-0.5 text-sm">
          {sections.map((s) => (
            <li key={s.id}>
              <button
                type="button"
                onClick={() => jumpTo(s.id)}
                className={`w-full rounded px-2 py-1.5 text-left ${
                  activeId === s.id
                    ? 'bg-brand-50 font-medium text-brand-700'
                    : 'text-slate-700 hover:bg-slate-100'
                }`}
              >
                {s.title}
              </button>
            </li>
          ))}
        </ul>
      </nav>

      <article ref={scrollerRef} className="overflow-y-auto px-10 py-8">
        <header className="border-b border-slate-200 pb-4">
          <h1 className="text-2xl font-semibold text-slate-900">Помощь</h1>
          <p className="mt-2 text-sm text-slate-600">
            Что умеет PriceWatch и как этим пользоваться. Каждый раздел — отдельная
            функция: что она делает, зачем нужна и как до неё добраться.
          </p>
        </header>

        <div className="mx-auto max-w-3xl space-y-12 py-8">
          {sections.map((s) => (
            <section
              key={s.id}
              id={`help-${s.id}`}
              data-section-id={s.id}
              className="scroll-mt-4"
            >
              <h2 className="text-lg font-semibold text-slate-900">{s.title}</h2>
              <div className="mt-3 space-y-3 text-sm leading-relaxed text-slate-700">
                {s.body}
              </div>
            </section>
          ))}

          <footer className="border-t border-slate-200 pt-4 text-xs text-slate-500">
            Что-то не работает или непонятно? Откройте раздел «Здоровье парсеров» —
            если успешность ниже 80%, скорее всего, изменилась вёрстка маркетплейса
            и парсер временно не достаёт нужные поля. Это лечится обновлением расширения.
          </footer>
        </div>
      </article>
    </div>
  );
}

